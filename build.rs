fn main() {
    println!("cargo::rustc-check-cfg=cfg(packed_assets)");

    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if arch == "wasm32" || os == "android" {
        println!("cargo::rustc-cfg=packed_assets");
    }

    // Sound is desktop-only: the sounds are 332 MB in an object store a
    // browser cannot reach, and rodio's backend is not built for these
    // targets. The `audio` feature is on by default and simply off there.
    println!("cargo::rustc-check-cfg=cfg(audio)");
    if std::env::var_os("CARGO_FEATURE_AUDIO").is_some() && arch != "wasm32" && os != "android" {
        println!("cargo::rustc-cfg=audio");
    }

    println!("cargo::rustc-check-cfg=cfg(voice)");
    if std::env::var_os("CARGO_FEATURE_VOICE").is_some() && arch != "wasm32" && os != "android" {
        println!("cargo::rustc-cfg=voice");
    }

    println!("cargo::rustc-check-cfg=cfg(resource_packs)");
    println!("cargo::rustc-check-cfg=cfg(explore_modrinth)");
    if std::env::var_os("CARGO_FEATURE_RESOURCEPACKS").is_some()
        && arch != "wasm32"
        && os != "android"
    {
        println!("cargo::rustc-cfg=resource_packs");
        if std::env::var_os("CARGO_FEATURE_EXPLORE_MODRINTH").is_some() {
            println!("cargo::rustc-cfg=explore_modrinth");
        }
    }

    if std::env::var_os("CARGO_FEATURE_VULKAN").is_some() {
        compile_slang();
    }
}

/// The Slang release the engine's shaders are written against
/// (VULKAN_REWRITE_CHECKLIST.md 2.6). Another version builds with a warning.
const SLANG_VERSION: &str = "2026.1";

/// Compiles every `shaders/*.slang` that has entry points to SPIR-V in
/// OUT_DIR, with its reflection JSON beside it, and writes `shaders.rs`
/// listing them for `include_bytes!`. Modules without entry points (the
/// shared ones) are only imported.
fn compile_slang() {
    use std::path::PathBuf;
    use std::process::Command;

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let dir = PathBuf::from("shaders");
    println!("cargo::rerun-if-changed=shaders");
    println!("cargo::rerun-if-env-changed=SLANGC");
    println!("cargo::rerun-if-env-changed=VULKAN_SDK");
    let slangc = std::env::var_os("SLANGC")
        .map(PathBuf::from)
        .or_else(|| {
            std::env::var_os("VULKAN_SDK").map(|sdk| PathBuf::from(sdk).join("Bin").join("slangc"))
        })
        .unwrap_or_else(|| PathBuf::from("slangc"));
    match Command::new(&slangc).arg("-version").output() {
        Ok(version) => {
            let text = String::from_utf8_lossy(&version.stdout).to_string()
                + &String::from_utf8_lossy(&version.stderr);
            if !text.trim().starts_with(SLANG_VERSION) {
                println!(
                    "cargo::warning=slangc is {}, the shaders expect {SLANG_VERSION}",
                    text.trim()
                );
            }
        }
        Err(e) => {
            panic!("the `vulkan` feature needs slangc (from the Vulkan SDK, or set SLANGC): {e}")
        }
    }
    let mut listing = String::from("// Generated by build.rs from shaders/*.slang.\n");
    let mut reflections = Vec::new();
    let mut entries: Vec<_> = std::fs::read_dir(&dir)
        .expect("a shaders folder")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "slang"))
        .collect();
    entries.sort();
    for path in entries {
        let source = std::fs::read_to_string(&path).expect("a readable shader");
        if !source.contains("[shader(") {
            continue;
        }
        let stem = path.file_stem().unwrap().to_string_lossy().into_owned();
        let spv = out.join(format!("{stem}.spv"));
        let json = out.join(format!("{stem}.json"));
        let output = Command::new(&slangc)
            .arg(&path)
            .args(["-target", "spirv", "-profile", "spirv_1_5"])
            .args(["-fvk-use-entrypoint-name", "-matrix-layout-column-major"])
            // Slang widens the profile for texture types; only the capabilities
            // a shader uses reach the module.
            .args(["-warnings-disable", "41012"])
            .arg("-I")
            .arg(&dir)
            .arg("-o")
            .arg(&spv)
            .arg("-reflection-json")
            .arg(&json)
            .output()
            .expect("slangc runs");
        if !output.status.success() {
            panic!(
                "slangc failed on {}:\n{}{}",
                path.display(),
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            );
        }
        let name = stem.to_uppercase();
        reflections.push(format!("(\"{stem}\", {name}_REFLECTION)"));
        listing.push_str(&format!(
            "pub const {name}: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{stem}.spv\"));\n\
             pub const {name}_REFLECTION: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/{stem}.json\"));\n"
        ));
    }
    listing.push_str(&format!(
        "/// Every shader's reflection, by name, for the layout tests.\n\
         pub const REFLECTIONS: &[(&str, &str)] = &[{}];\n",
        reflections.join(", ")
    ));
    std::fs::write(out.join("shaders.rs"), listing).expect("writes shaders.rs");
}
