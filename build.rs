fn main() {
    println!("cargo::rustc-check-cfg=cfg(packed_assets)");

    let os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    if os == "android" {
        println!("cargo::rustc-cfg=packed_assets");
    }

    // Sound on every OS (Android through cpal's Oboe backend).
    println!("cargo::rustc-check-cfg=cfg(audio)");
    if std::env::var_os("CARGO_FEATURE_AUDIO").is_some() {
        println!("cargo::rustc-cfg=audio");
        // Oboe links libc++ statically, but not its ABI half (`__cxa_*`).
        if os == "android" {
            println!("cargo::rustc-link-lib=c++abi");
        }
    }

    println!("cargo::rustc-check-cfg=cfg(voice)");
    if std::env::var_os("CARGO_FEATURE_VOICE").is_some() && os != "android" {
        println!("cargo::rustc-cfg=voice");
    }

    println!("cargo::rustc-check-cfg=cfg(resource_packs)");
    println!("cargo::rustc-check-cfg=cfg(explore_modrinth)");
    if std::env::var_os("CARGO_FEATURE_RESOURCEPACKS").is_some() && os != "android" {
        println!("cargo::rustc-cfg=resource_packs");
        if std::env::var_os("CARGO_FEATURE_EXPLORE_MODRINTH").is_some() {
            println!("cargo::rustc-cfg=explore_modrinth");
        }
    }

    if std::env::var_os("CARGO_FEATURE_VULKAN").is_some() {
        let slangc = find_slangc();
        compile_slang(&slangc);
        if std::env::var_os("CARGO_FEATURE_SHADER_SUPPORT").is_some() {
            compile_torch_pack(&slangc, os == "android");
        }
    }
}

/// The Slang release the engine's shaders are written against
/// (VULKAN_REWRITE_CHECKLIST.md 2.6). Another version builds with a warning.
const SLANG_VERSION: &str = "2026.1";

/// Compiles every `shaders/*.slang` that has entry points to SPIR-V in
/// OUT_DIR, with its reflection JSON beside it, and writes `shaders.rs`
/// listing them for `include_bytes!`. Modules without entry points (the
/// shared ones) are only imported.
fn compile_slang(slangc: &std::path::Path) {
    use std::path::PathBuf;
    use std::process::Command;

    let out = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"));
    let dir = PathBuf::from("shaders");
    println!("cargo::rerun-if-changed=shaders");
    let mut listing = String::from("// Generated by build.rs from shaders/*.slang.\n");
    let mut reflections = Vec::new();
    let mut entries: Vec<_> = std::fs::read_dir(&dir)
        .expect("a shaders folder")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "slang"))
        .collect();
    entries.sort();
    for path in entries {
        let source = std::fs::read_to_string(&path).expect("a readable shader");
        if !source.contains("[shader(") {
            continue;
        }
        let stem = path.file_stem().unwrap().to_string_lossy().into_owned();
        let spv = out.join(format!("{stem}.spv"));
        let json = out.join(format!("{stem}.json"));
        let output = Command::new(slangc)
            .arg(&path)
            .args(["-target", "spirv", "-profile", "spirv_1_3"])
            .args(["-fvk-use-entrypoint-name", "-matrix-layout-column-major"])
            // Slang widens the profile for texture types; only the capabilities
            // a shader uses reach the module (41012). The read-only view of
            // the bindless buffers shares their binding on purpose (39001).
            .args(["-warnings-disable", "41012,39001"])
            .arg("-I")
            .arg(&dir)
            .arg("-o")
            .arg(&spv)
            .arg("-reflection-json")
            .arg(&json)
            .output()
            .expect("slangc runs");
        if !output.status.success() {
            panic!(
                "slangc failed on {}:\n{}{}",
                path.display(),
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            );
        }
        let name = stem.to_uppercase();
        reflections.push(format!("(\"{stem}\", {name}_REFLECTION)"));
        listing.push_str(&format!(
            "pub const {name}: &[u8] = include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{stem}.spv\"));\n\
             pub const {name}_REFLECTION: &str = include_str!(concat!(env!(\"OUT_DIR\"), \"/{stem}.json\"));\n"
        ));
    }
    listing.push_str(&format!(
        "/// Every shader's reflection, by name, for the layout tests.\n\
         pub const REFLECTIONS: &[(&str, &str)] = &[{}];\n",
        reflections.join(", ")
    ));
    std::fs::write(out.join("shaders.rs"), listing).expect("writes shaders.rs");
}

/// slangc from `SLANGC`, the Vulkan SDK, or the path, warning when it is not
/// the release the shaders are written against.
fn find_slangc() -> std::path::PathBuf {
    use std::path::PathBuf;
    println!("cargo::rerun-if-env-changed=SLANGC");
    println!("cargo::rerun-if-env-changed=VULKAN_SDK");
    let slangc = std::env::var_os("SLANGC")
        .map(PathBuf::from)
        .or_else(|| {
            std::env::var_os("VULKAN_SDK").map(|sdk| PathBuf::from(sdk).join("Bin").join("slangc"))
        })
        .unwrap_or_else(|| PathBuf::from("slangc"));
    match std::process::Command::new(&slangc).arg("-version").output() {
        Ok(version) => {
            let text = String::from_utf8_lossy(&version.stdout).to_string()
                + &String::from_utf8_lossy(&version.stderr);
            if !text.trim().starts_with(SLANG_VERSION) {
                println!(
                    "cargo::warning=slangc is {}, the shaders expect {SLANG_VERSION}",
                    text.trim()
                );
            }
        }
        Err(e) => {
            panic!("the `vulkan` feature needs slangc (from the Vulkan SDK, or set SLANGC): {e}")
        }
    }
    slangc
}

/// Compiles the built-in pack (`src/shaderpack/builtin/pack`) to SPIR-V,
/// one module per program, input and stage, behind the engine's prelude
/// (`builtin/iris`), and writes `torch_pack/modules.rs` listing them by
/// `<program>.<input>.<stage>`. Drawing programs build for both terrain
/// and entity input, since the engine may draw either kind with one
/// program; screen passes and compute programs build for their own.
fn compile_torch_pack(slangc: &std::path::Path, android: bool) {
    use std::path::PathBuf;

    let out =
        PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("torch_pack");
    std::fs::create_dir_all(&out).expect("creates the pack's output folder");
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("cargo sets it"))
        .join("src/shaderpack/builtin");
    println!("cargo::rerun-if-changed=src/shaderpack/builtin/iris");
    println!("cargo::rerun-if-changed=src/shaderpack/builtin/pack");
    let pack = root.join("pack");
    let mut programs: Vec<String> = std::fs::read_dir(&pack)
        .expect("the pack's folder")
        .filter_map(Result::ok)
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "slang"))
        .map(|p| p.file_stem().unwrap().to_string_lossy().into_owned())
        .collect();
    programs.sort();

    let mut jobs: Vec<(String, &str, &str)> = Vec::new();
    for program in &programs {
        let text =
            std::fs::read_to_string(pack.join(format!("{program}.slang"))).expect("readable");
        if text.contains("[numthreads(") {
            jobs.push((program.clone(), "compute", "compute"));
            continue;
        }
        let screen = [
            "deferred",
            "composite",
            "final",
            "prepare",
            "begin",
            "setup",
        ]
        .iter()
        .any(|p| program.starts_with(p));
        let inputs: &[&str] = if screen {
            &["screen"]
        } else {
            &["terrain", "entity"]
        };
        for input in inputs {
            jobs.push((program.clone(), input, "vertex"));
            jobs.push((program.clone(), input, "fragment"));
        }
    }

    let failures = std::sync::Mutex::new(Vec::new());
    let next = std::sync::atomic::AtomicUsize::new(0);
    let threads = std::thread::available_parallelism().map_or(4, |n| n.get());
    std::thread::scope(|scope| {
        for _ in 0..threads {
            scope.spawn(|| {
                loop {
                    let at = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                    let Some((program, input, stage)) = jobs.get(at) else {
                        break;
                    };
                    let key = format!("{program}.{input}.{stage}");
                    let wrapper = out.join(format!("{key}.slang"));
                    let mut text = String::from("#include \"iris/iris.slang\"\n");
                    if *input != "compute" {
                        text.push_str(&format!("#include \"iris/{input}.slang\"\n"));
                    }
                    text.push_str(&format!("#include \"pack/{program}.slang\"\n"));
                    std::fs::write(&wrapper, text).expect("writes the wrapper");
                    let mut command = std::process::Command::new(slangc);
                    command
                        .arg(&wrapper)
                        .args(["-D", "TORCH_SLANG"])
                        .args(["-entry", stage, "-stage", stage])
                        .args(["-target", "spirv", "-profile", "spirv_1_3"])
                        .arg("-matrix-layout-column-major")
                        // As `compile_slang`: widened profiles (41012) and the
                        // read-write view sharing the buffers' binding (39001).
                        .args(["-warnings-disable", "41012,39001"])
                        .arg("-I")
                        .arg(&root)
                        .arg("-o")
                        .arg(out.join(format!("{key}.spv")));
                    if android {
                        command.args(["-D", "MC_OS_ANDROID"]);
                    }
                    let output = command.output().expect("slangc runs");
                    if !output.status.success() {
                        failures.lock().unwrap().push(format!(
                            "{key}:\n{}{}",
                            String::from_utf8_lossy(&output.stdout),
                            String::from_utf8_lossy(&output.stderr)
                        ));
                    }
                }
            });
        }
    });
    let failures = failures.into_inner().unwrap();
    if !failures.is_empty() {
        panic!(
            "slangc failed on the built-in pack:\n{}",
            failures.join("\n")
        );
    }

    let mut listing = String::from(
        "// Generated by build.rs from src/shaderpack/builtin.\n\
         pub(crate) const MODULES: &[(&str, &[u8])] = &[\n",
    );
    for (program, input, stage) in &jobs {
        let key = format!("{program}.{input}.{stage}");
        listing.push_str(&format!(
            "    (\"{key}\", include_bytes!(concat!(env!(\"OUT_DIR\"), \"/torch_pack/{key}.spv\"))),\n"
        ));
    }
    listing.push_str("];\n");
    std::fs::write(out.join("modules.rs"), listing).expect("writes the pack's listing");
}
