#!/usr/bin/env python3
"""Generate `src/blockentities/sim/piston/push_reactions.rs` from the game itself.

Blocks.java no longer names its blocks inline, so rather than parse it this
reads what `tools/DumpGameData.java` prints when run against a server jar:

    cd <the folder the server jar unpacked into, holding versions/ and libraries/>
    javac -cp "versions/<v>/server-<v>.jar:libraries/..." -d . <crate>/tools/DumpGameData.java
    java  -cp "versions/<v>/server-<v>.jar:libraries/...:." DumpGameData > game.txt
    python3 gen_push_reactions.py game.txt > <crate>/src/blockentities/sim/piston/push_reactions.rs

Each dumped line is `<block> <PushReaction> <hasBlockEntity>` for the default
state, possibly behind a log prefix.
"""

import re
import sys

# 26.3's names on the left, the piston simulation's on the right.
REACTIONS = {
    "PUSH_PULL": "Normal",
    "POPPED": "Destroy",
    "IMMOVEABLE": "Block",
    "PUSH": "PushOnly",
    "IGNORE_ENTITY": "Normal",
}

LINE = re.compile(r"([a-z0-9_]+) ([A-Z_]+) (true|false)\s*$")


def main():
    by, entity = {}, []
    with open(sys.argv[1], encoding="utf-8") as dump:
        for line in dump:
            m = LINE.search(line)
            if not m:
                continue
            block, reaction, has_entity = m.groups()
            if reaction not in REACTIONS:
                sys.exit(f"unknown push reaction {reaction} on {block}")
            r = REACTIONS[reaction]
            if r != "Normal":
                by.setdefault(r, []).append(block)
            if has_entity == "true":
                entity.append(block)
    if not entity:
        sys.exit("no blocks were read; is this the DumpGameData output?")

    w = sys.stdout.write
    w("//! Generated by `tools/gen_push_reactions.py` from `tools/DumpGameData.java`.\n\n")
    w("use super::PushReaction;\n\n")
    w("/// `BlockBehaviour.getPistonPushReaction`, by block id.\n")
    w("pub(super) fn push_reaction(id: &str) -> PushReaction {\n    match id {\n")
    for r in sorted(by):
        names = sorted(by[r])
        w("        " + "\n        | ".join('"%s"' % n for n in names))
        w(" => PushReaction::%s,\n" % r)
    w("        _ => PushReaction::Normal,\n    }\n}\n\n")
    w("/// `BlockStateBase.hasBlockEntity`, by block id.\n")
    w("pub(super) fn has_block_entity(id: &str) -> bool {\n    matches!(\n        id,\n        ")
    w("\n            | ".join('"%s"' % n for n in sorted(entity)))
    w("\n    )\n}\n")


main()
