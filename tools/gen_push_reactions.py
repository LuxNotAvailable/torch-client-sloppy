#!/usr/bin/env python3

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BLOCK = ROOT / "reference/minecraft-26.1.1/net/minecraft/world/level/block"

def statements(body):
    out, depth, start = [], 0, 0
    for i, c in enumerate(body):
        if c in "({":
            depth += 1
        elif c in ")}":
            depth -= 1
        elif c == ";" and depth == 0:
            out.append(body[start:i].strip())
            start = i + 1
    return out

def helpers(src):
    found = {}
    for m in re.finditer(r"(?:private|public) static [\w.<>?]+ (\w+)\([^)]*\) \{", src):
        depth, i = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(src[i], 0)
            i += 1
        reaction = re.findall(r"pushReaction\(PushReaction\.(\w+)\)", src[m.end():i])
        if reaction:
            found[m.group(1)] = reaction[-1]
    return found

def main():
    src = (BLOCK / "Blocks.java").read_text()
    helper = helpers(src)
    static = src[src.index("   static {"):]
    ids, reaction = {}, {}
    for st in statements(static[static.index("{") + 1:]):
        m = re.match(r"(\w+) = (\w+)\((?:BlockIds\.(\w+)|\"([a-z0-9_]+)\")", st)
        if not m:
            continue
        const, call = m.group(1), m.group(2)
        name = m.group(4) or m.group(3).lower()
        ids[const] = name
        direct = re.findall(r"pushReaction\(PushReaction\.(\w+)\)", st)
        copy = re.search(r"of(?:Full|Legacy)Copy\((\w+)\)", st)
        stair = re.match(r"\w+ = register(?:Legacy)?Stair\(\"[a-z0-9_]+\", (\w+)\)", st)
        used = [h for h in helper if re.search(r"\b%s\(" % h, st)]
        if direct:
            r = direct[-1]
        elif used:
            r = helper[used[0]]
        elif copy:
            r = reaction.get(copy.group(1), "NORMAL")
        elif stair:
            r = reaction.get(stair.group(1), "NORMAL")
        else:
            r = "NORMAL"
        reaction[const] = r

    bet = (BLOCK / "entity/BlockEntityType.java").read_text()
    entity = sorted({ids[c] for c in re.findall(r"Blocks\.(\w+)", bet) if c in ids})

    by = {}
    for const, r in reaction.items():
        if r != "NORMAL":
            by.setdefault(r, []).append(ids[const])

    w = sys.stdout.write
    w("//! Generated by `tools/gen_push_reactions.py` from Blocks.java and BlockEntityType.java.\n\n")
    w("use super::PushReaction;\n\n")
    w("/// `BlockBehaviour.getPistonPushReaction`, by block id.\n")
    w("pub(super) fn push_reaction(id: &str) -> PushReaction {\n    match id {\n")
    for r in sorted(by):
        names = sorted(by[r])
        w("        " + "\n        | ".join('"%s"' % n for n in names))
        w(" => PushReaction::%s,\n" % r.title().replace("_", ""))
    w("        _ => PushReaction::Normal,\n    }\n}\n\n")
    w("/// `BlockStateBase.hasBlockEntity`, by block id.\n")
    w("pub(super) fn has_block_entity(id: &str) -> bool {\n    matches!(\n        id,\n        ")
    w("\n            | ".join('"%s"' % n for n in entity))
    w("\n    )\n}\n")

main()
