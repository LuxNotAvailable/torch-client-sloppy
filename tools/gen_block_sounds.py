#!/usr/bin/env python3
"""Generate `src/generated_block_sounds.rs` from the game itself.

Reads the `sound` lines `tools/DumpGameData.java` prints (see
`gen_push_reactions.py` for running it against a server jar):

    python3 tools/gen_block_sounds.py game.txt > src/generated_block_sounds.rs

Each `sound <block> <volume> <pitch> <break> <step> <place> <hit> <fall>`
line is the default state's `SoundType`; identical sound types are emitted
once and blocks map to them. Each `use <block> <kind> <byHand> <on> <off>`
line is a door, trapdoor, fence gate or button's open and close (or press
and release) sounds from its `BlockSetType` or `WoodType`.
"""

import re
import sys

USE = re.compile(r"use ([a-z0-9_]+) (door|trapdoor|fence_gate|button) (true|false) ([a-z0-9_./]+) ([a-z0-9_./]+)\s*$")
LINE = re.compile(r"sound ([a-z0-9_]+) ([0-9.]+) ([0-9.]+) ((?:[a-z0-9_./]+ ?){5})\s*$")


def ident(events):
    # Named after the break event, which is unique enough across types.
    base = events[0].replace("block.", "").replace("item.", "").replace(".break", "")
    return re.sub(r"[^A-Z0-9]+", "_", base.upper()).strip("_")


def main():
    types, blocks, uses = {}, [], []
    with open(sys.argv[1], encoding="utf-8") as dump:
        for line in dump:
            u = USE.search(line)
            if u:
                uses.append(u.groups())
                continue
            m = LINE.search(line)
            if not m:
                continue
            block, volume, pitch, events = m.groups()
            key = (float(volume), float(pitch), tuple(events.split()))
            types.setdefault(key, None)
            blocks.append((block, key))
    if not blocks:
        sys.exit("no sound lines were read; is this the DumpGameData output?")

    names, used = {}, set()
    for key in types:
        name = ident(key[2])
        while name in used:
            name += "_"
        used.add(name)
        names[key] = name

    w = sys.stdout.write
    w("//! Generated by `tools/gen_block_sounds.py` from `tools/DumpGameData.java`.\n")
    w("//! Each block's default `SoundType`.\n\n")
    w("use crate::util::block_model::SoundGroup;\n\n")
    for key, name in names.items():
        volume, pitch, (brk, step, place, hit, fall) = key
        w(f"static {name}: SoundGroup = SoundGroup {{\n")
        w(f"    volume: {volume!r},\n    pitch: {pitch!r},\n")
        w(f'    break_event: "{brk}",\n    step_event: "{step}",\n')
        w(f'    place_event: "{place}",\n    hit_event: "{hit}",\n')
        w(f'    fall_event: "{fall}",\n}};\n')
    w("\n/// `BlockState.getSoundType` of the block's default state, by id.\n")
    w("pub fn sound_group(id: &str) -> &'static SoundGroup {\n    match id {\n")
    by_type = {}
    for block, key in blocks:
        by_type.setdefault(names[key], []).append(block)
    default = names[max(types, key=lambda k: sum(1 for _, b in blocks if b == k))]
    for name, members in sorted(by_type.items()):
        if name == default:
            continue
        w("        " + "\n        | ".join(f'"{b}"' for b in sorted(members)))
        w(f" => &{name},\n")
    w(f"        _ => &{default},\n    }}\n}}\n")

    w("\n/// What a hand-used door, trapdoor, fence gate or button sounds like.\n")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum UseKind {\n")
    w("    Door,\n    Trapdoor,\n    FenceGate,\n    Button,\n}\n\n")
    w("pub struct UseSounds {\n    pub kind: UseKind,\n")
    w("    /// `BlockSetType.canOpenByHand`: iron doors and trapdoors can't.\n")
    w("    pub by_hand: bool,\n    /// Opening, or pressing.\n    pub on: &'static str,\n")
    w("    /// Closing, or releasing.\n    pub off: &'static str,\n}\n\n")
    w("/// The block's use sounds, if it's a door, trapdoor, fence gate or button.\n")
    w("pub fn use_sounds(id: &str) -> Option<UseSounds> {\n    let (kind, by_hand, on, off) = match id {\n")
    kinds = {"door": "Door", "trapdoor": "Trapdoor", "fence_gate": "FenceGate", "button": "Button"}
    for block, kind, by_hand, on, off in sorted(uses):
        w(f'        "{block}" => (UseKind::{kinds[kind]}, {by_hand}, "{on}", "{off}"),\n')
    w("        _ => return None,\n    };\n")
    w("    Some(UseSounds {\n        kind,\n        by_hand,\n        on,\n        off,\n    })\n}\n")


if __name__ == "__main__":
    main()
